#!/usr/bin/env python3
"""Pack flower1.png, flower2.png, flower3.png into assets/flowers.js.

The grass layer is drawn with WebGL, and browsers won't let WebGL read image
files when the page is opened straight from disk (file://). Images embedded as
data URLs are fine, so this script embeds the PNGs into a small script file.

Run it again after editing any of the flower PNGs:
    python3 tools/build-flowers.py
"""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sprites = []
for i in (1, 2, 3):
    data = (root / f'flower{i}.png').read_bytes()
    sprites.append('data:image/png;base64,' + base64.b64encode(data).decode())

out = root / 'assets' / 'flowers.js'
out.write_text(
    '// generated by tools/build-flowers.py from flower1.png, flower2.png, flower3.png\n'
    'window.FLOWER_SPRITES = ' + json.dumps(sprites) + ';\n'
)
print(f'wrote {out.relative_to(root)} ({out.stat().st_size // 1024} KB)')
